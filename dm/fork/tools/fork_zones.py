#!/usr/bin/env python3
# FORK v55: dm/host/fork_zones.h, Sword / Shield zone hashes -> met location and English name, for the area dex (host/fork_dex.c).
# Source: pkNX pkNX.Game/Misc/SWSHInfo.cs (ZoneLocations, Zones; GPLv3, https://github.com/kwsch/pkNX). The hashes are names of places, not game data:
# the encounter tables themselves are read on the phone from the player's own RomFS.
# Usage: python3 fork_zones.py SWSHInfo.cs > dm/host/fork_zones.h
import re, sys
src = open(sys.argv[1], encoding='utf-8-sig').read()
def block(name):
    i = src.index(name); j = src.index('};', i); return src[i:j]
locs = {int(h, 16): int(v, 10) for h, v in re.findall(r'\{\s*0x([0-9A-Fa-f]+)\s*,\s*(\d+)\s*\}', block('ZoneLocations'))}
names = {int(h, 16): n for h, n in re.findall(r'\{\s*0x([0-9A-Fa-f]+)\s*,\s*"([^"]*)"\s*\}', block('Zones ='))}
print('// FORK v55: generated by dm/fork/tools/fork_zones.py from pkNX SWSHInfo.cs (GPLv3): zone hash, met location, name. Do not edit.')
print('typedef struct { uint64_t hash; uint8_t loc; const char *name; } fork_zone;')
print('static const fork_zone k_zones[] = {')
for h in sorted(set(locs) | set(names)):
    n = names.get(h, '').replace('\\', '').replace('"', "'")
    print(f'    {{ 0x{h:016X}ull, {locs.get(h, 0)}, "{n}" }},')
print('};')
